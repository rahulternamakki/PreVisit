-- ==============================================================================
-- PreVisit Database Schema - Phase 1: Patient Intakes Table & Security
-- ==============================================================================
-- Table: intakes
-- Purpose: Persistent storage for patient intakes, conversational transcripts,
--          structured clinical summaries, red-flag risks, and triage urgency.
-- Security: Strict Row Level Security (RLS) enabled with NO public access.
--           Only the Python FastAPI backend using the Supabase Service Role Key
--           can read, insert, update, or delete intake records.
-- ==============================================================================

-- 1. Enable required extensions for UUID generation (if using PostgreSQL < 13)
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. Create the `intakes` table with strict data integrity checks
CREATE TABLE IF NOT EXISTS public.intakes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    patient_name TEXT NOT NULL CHECK (char_length(trim(patient_name)) > 0),
    patient_age INTEGER NOT NULL CHECK (patient_age >= 0 AND patient_age <= 130),
    chief_complaint TEXT DEFAULT NULL,
    chat_transcript JSONB NOT NULL DEFAULT '[]'::jsonb 
        CHECK (jsonb_typeof(chat_transcript) = 'array'),
    summary JSONB DEFAULT NULL 
        CHECK (summary IS NULL OR jsonb_typeof(summary) = 'object'),
    red_flags JSONB NOT NULL DEFAULT '[]'::jsonb 
        CHECK (jsonb_typeof(red_flags) = 'array'),
    urgency_level TEXT NOT NULL DEFAULT 'routine' 
        CHECK (urgency_level IN ('routine', 'urgent', 'emergency')),
    status TEXT NOT NULL DEFAULT 'in_progress' 
        CHECK (status IN ('in_progress', 'completed', 'reviewed', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Documentation comments
COMMENT ON TABLE public.intakes IS 'Stores patient intake records, full transcripts, clinical summaries, and red-flag evaluations.';
COMMENT ON COLUMN public.intakes.id IS 'Unique identifier for the intake session (UUID).';
COMMENT ON COLUMN public.intakes.patient_name IS 'Full name of the patient undergoing intake.';
COMMENT ON COLUMN public.intakes.patient_age IS 'Age of the patient in years (0 - 130).';
COMMENT ON COLUMN public.intakes.chief_complaint IS 'Patient primary stated complaint or concern.';
COMMENT ON COLUMN public.intakes.chat_transcript IS 'Full chat transcript as a JSON array of message objects [{"role": "user"|"assistant", "content": "...", "timestamp": "..."}].';
COMMENT ON COLUMN public.intakes.summary IS 'Validated structured clinical summary generated by Groq LLM.';
COMMENT ON COLUMN public.intakes.red_flags IS 'JSON array of identified red flags with patient direct quotes.';
COMMENT ON COLUMN public.intakes.urgency_level IS 'Triage urgency level: routine, urgent, or emergency.';
COMMENT ON COLUMN public.intakes.status IS 'Lifecycle state: in_progress, completed, reviewed, archived.';
COMMENT ON COLUMN public.intakes.created_at IS 'Timestamp of intake creation in UTC.';
COMMENT ON COLUMN public.intakes.updated_at IS 'Timestamp of latest update in UTC.';

-- 3. Automatic updated_at timestamp trigger
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_set_intakes_updated_at ON public.intakes;
CREATE TRIGGER trigger_set_intakes_updated_at
    BEFORE UPDATE ON public.intakes
    FOR EACH ROW
    EXECUTE FUNCTION public.set_updated_at();

-- 4. Performance Indexes
-- Index for status filtering (e.g. completed intakes for doctor queue)
CREATE INDEX IF NOT EXISTS idx_intakes_status ON public.intakes (status);

-- Index for urgency level filtering and sorting
CREATE INDEX IF NOT EXISTS idx_intakes_urgency_level ON public.intakes (urgency_level);

-- Index for chronology / timestamp sorting
CREATE INDEX IF NOT EXISTS idx_intakes_created_at ON public.intakes (created_at DESC);

-- Composite Index: Doctor dashboard triage queue (completed items sorted with urgent first, then by date)
CREATE INDEX IF NOT EXISTS idx_intakes_doctor_queue 
    ON public.intakes (status, urgency_level, created_at DESC);

-- GIN Indexes: Efficient querying into JSON arrays if searching transcripts or red flags
CREATE INDEX IF NOT EXISTS idx_intakes_chat_transcript_gin 
    ON public.intakes USING gin (chat_transcript);
CREATE INDEX IF NOT EXISTS idx_intakes_red_flags_gin 
    ON public.intakes USING gin (red_flags);

-- 5. Row-Level Security (RLS) & Strict Access Control
-- Enable and force Row Level Security
ALTER TABLE public.intakes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.intakes FORCE ROW LEVEL SECURITY;

-- Revoke all direct permissions from public API roles (anon and authenticated).
-- This guarantees the frontend or any public client cannot query or mutate intakes directly.
REVOKE ALL ON TABLE public.intakes FROM anon;
REVOKE ALL ON TABLE public.intakes FROM authenticated;

-- Explicit restrictive denial policy visible in Supabase dashboard
DROP POLICY IF EXISTS "Deny public and authenticated direct access" ON public.intakes;
CREATE POLICY "Deny public and authenticated direct access"
    ON public.intakes
    AS RESTRICTIVE
    FOR ALL
    TO anon, authenticated
    USING (false);

-- Grant full access exclusively to service_role (used by Python backend) and database admin (postgres)
GRANT ALL ON TABLE public.intakes TO service_role;
GRANT ALL ON TABLE public.intakes TO postgres;
